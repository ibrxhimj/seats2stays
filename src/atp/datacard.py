"""Generate reports/data_card.md from the ledger (never hand-edited)."""
import pandas as pd
from .ledger import Ledger

GRAIN = {
    "flights_rows": "one row per (date, departure city, airline); 2022 monthly, 2023+ daily",
    "flights_day_quality": "one row per day (2023+): route-row count and coverage flags",
    "flights_country_daily": "country × day, 2023-01-01…2026-02-28, complete grid (daily only)",
    "flights_country_monthly": "country × month, 2022-01…2026-02 (monthly source for 2022, daily-summed after)",
    "hotel_intl_daily": "nationality × day, 2022-01-01…2026-02-28, complete grid",
    "hotel_dom_daily": "one row per day, 2022-01-01…2026-02-28",
    "hotel_monthly": "market × nationality × month",
    "country_map": "one row per hotel nationality",
    "calendar_events": "one row per holiday/event window, with source",
    "calendar": "one row per day, 2021-11-01…2027-12-31",
    "external_events": "one row per real-world event audited against the data",
}


def write(T: dict, led: Ledger, cfg: dict, digests: dict, path):
    L = ["# Data card — Seats2Stays flight → hotel demand simulator (ATP 2026)", "",
         "_Generated by `make data` from the raw files; do not edit by hand._", "",
         "## 1. Provenance", "", "| Raw file | SHA-256 (first 16) |", "|---|---|"]
    L += [f"| {k} | `{v[:16]}` |" for k, v in digests.items()]
    L += ["", "Raw files are read-only; every derived value below is reproducible from them.", "",
          "## 2. Tables produced (`data/processed/*.parquet`)", "", "| Table | Rows | Columns | Grain |", "|---|---|---|---|"]
    L += [f"| `{k}` | {len(v):,} | {v.shape[1]} | {GRAIN.get(k, '')} |" for k, v in T.items()]
    L += ["", "## 3. Cleaning and derivation rules", "", "| ID | Table | Rule | Rows affected |", "|---|---|---|---|"]
    L += [f"| {r[0]} | `{r[1]}` | {r[2]} | {r[3] if isinstance(r[3], str) else f'{r[3]:,}'} |" for r in led.rules]
    n_err = sum(1 for c in led.checks if c[1] == "error")
    n_ok = sum(1 for c in led.checks if c[1] == "error" and c[2])
    L += ["", f"## 4. Automated checks — {n_ok}/{n_err} blocking checks passed", "", "| Check | Severity | Result | Detail |", "|---|---|---|---|"]
    L += [f"| `{c[0]}` | {c[1]} | {'PASS' if c[2] else ('FAIL' if c[1] == 'error' else 'WARN')} | {c[3]} |" for c in led.checks]
    f = led.facts
    L += ["", "## 5. Key facts", "",
          f"- Load factor > 1 on {f['lf_gt1_rows']:,} flight rows; still > 1 on {f['lf_excl_infant_gt1_rows']:,} rows after removing infants "
          "(so infants explain only part of it — overbooking/crew/reporting). Raw and capped LF are both kept.",
          f"- Suppression: hidden training cells can hold at most {f['suppressed_guest_share_upper_bound']:.4%} of training guests; "
          f"hidden test arrivals at most {f['test_hidden_arrivals_share_upper_bound']:.3%} of test arrivals. "
          f"Hidden arrivals filled with {f['hidden_arrivals_fill_value']:g}.",
          f"- Arrivals status counts: " + ", ".join(f"{k.split(':')[1]} {v:,}" for k, v in f.items() if k.startswith("arrivals_status:")),
          f"- Nationalities with no flight data in the pack ({len(f['no_flight_data_nationalities'])}): " + ", ".join(x.title() for x in f["no_flight_data_nationalities"])
          + " (not the same as having no direct route to Abu Dhabi)",
          f"- Ramadan inside the official test window: {f['ramadan_days_in_test_window']} days, starting {f['ramadan_start_in_test_window']} "
          "(no training February contains Ramadan).",
          f"- Flight rows with airline 'Unknown': {f['airline_unknown_rows']:,}."]
    L += ["- Coverage vs official totals: " + " | ".join(f["coverage_vs_official"]),
          "- Average length of stay vs DCT: " + " | ".join(f["alos_vs_official"]) + ". 2023 and 2025 match; 2022 differs "
          "(COVID-era long international stays in our data); the 2024 DCT figure (3.2) breaks its own 2.7→2.8→3.2→2.9 "
          "series while our data is flat at 2.84–2.90 — likely a misquoted figure, to confirm with DCT."]
    if f.get("calendar_official_changes"):
        L += ["- Official calendar changes vs algorithm: " + "; ".join(f["calendar_official_changes"])]
    ext = T["external_events"]
    L += ["", "## 6. External events audit", "", "Real-world events checked against the data before modelling "
          "(`data/reference/external_events.csv`). Event ratios compare the event window (3 days before start to end) with the "
          "same weekdays 2 and 3 weeks before and after; stay ratio = guests ÷ arrivals over the window vs that baseline.", "", "| Event | Dates | Evidence in data | Decision |", "|---|---|---|---|"]
    L += [f"| {r.event} | {r.start_date.date()}…{r.end_date.date()} | {r.evidence_in_data} | {r.decision} |" for r in ext.itertuples()]
    L += ["", "## 7. Modelling conventions fixed here", "",
          "- **Guests** = guests in-house that night (inferred: Guests ≥ arrivals on every train row with observed arrivals; Guests/arrivals ≈ stay length). "
          "Monthly guest nights = sum of daily Guests.",
          "- **Training starts 2023-01-01** (2022 = COVID recovery; flights monthly only). 2022 hotel arrivals remain available as lags.",
          "- **Daily flight features exist only from 2023-01-01**; 2022 flight data is used only at monthly grain.",
          "- **All lags by date arithmetic** (`atp.lags`); stock-flow lag windows verified for every market and fold.",
          "- **Validation folds**: A (primary, Aug–Feb season), B (Jan–Jul), final (official test).",
          "", "## 8. Open items", "",
          "- DCT mentors: exact definition of Guests; scoring grain; which nationalities make up the ~12% of hotel guests "
          "outside the pack; monthly room supply/occupancy; missing event calendar promised in the brief.",
          ""]
    path.write_text("\n".join(L), encoding="utf-8")
